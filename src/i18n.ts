import { useLocalState } from './kit';

export type Lang = 'ar' | 'en';

let current: Lang = 'ar';
export function syncLang(l: Lang): void { current = l; }
export function getLang(): Lang { return current; }

export function detectLang(): Lang {
    try {
        return /^en/i.test(navigator.language ?? '') ? 'en' : 'ar';
    } catch {
        return 'ar';
    }
}

export function useLang(): [Lang, (l: Lang) => void] {
    const [lang, setLang] = useLocalState<Lang>('tutora.lang.v1', detectLang());
    return [lang === 'en' ? 'en' : 'ar', setLang];
}

